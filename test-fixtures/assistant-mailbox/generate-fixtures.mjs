function utf16BeHex(text) {
  let hex = '';
  for (const char of text) {
    const cp = char.codePointAt(0);
    if (cp > 0xffff) {
      const v = cp - 0x10000;
      hex += (0xd800 + (v >> 10)).toString(16).padStart(4, '0');
      hex += (0xdc00 + (v & 0x3ff)).toString(16).padStart(4, '0');
    } else {
      hex += cp.toString(16).padStart(4, '0');
    }
  }
  return hex.toUpperCase();
}

function makeEmbeddedFontPdf({ title, fontName, font, glyphsByCp, lines }) {
  // font: { data (Buffer), format ('truetype' | 'cff'), ascent, descent,
  // capHeight, bbox }. data is the full font program for 'truetype' and
  // the bare CFF program for 'cff', as the two stream types require.
  // glyphsByCp: code point -> [character code, width in 1/1000 em]. The
  // character code is a glyph id for a TrueType font and a CID for a
  // CID-keyed CFF font, matching the CIDFont subtype emitted below.
  // lines: { latin } drawn in Helvetica, or { glyphs: [{ cp, src }], size,
  // align } drawn in the embedded font; src is the text the glyph stands
  // for, recorded in the ToUnicode map so extraction returns real text.
  const used = new Map();
  const contentParts = [];
  let y = 740;
  for (const line of lines) {
    if (line.latin !== undefined) {
      contentParts.push(`BT /F1 11 Tf 72 ${y} Td (${pdfEscape(line.latin)}) Tj ET`);
    } else {
      const size = line.size ?? 12;
      let width = 0;
      const hexParts = [];
      for (const { cp, src } of line.glyphs) {
        const entry = glyphsByCp[cp];
        if (entry === undefined) {
          throw new Error(`embedded font has no glyph for U+${cp.toString(16).toUpperCase()}`);
        }
        const [code, glyphWidth] = entry;
        width += glyphWidth;
        hexParts.push(code.toString(16).padStart(4, '0'));
        const previous = used.get(code);
        if (previous !== undefined && previous.src !== src) {
          throw new Error(`character code ${code} would need two ToUnicode mappings`);
        }
        used.set(code, { width: glyphWidth, src });
      }
      const x = line.align === 'right' ? 540 - (width * size) / 1000 : 72;
      contentParts.push(`BT /F2 ${size} Tf 1 0 0 1 ${x.toFixed(2)} ${y} Tm <${hexParts.join('')}> Tj ET`);
    }
    y -= line.gapAfter ?? 26;
  }
  const content = Buffer.from(contentParts.join('\n'), 'ascii');

  const sortedUsed = [...used.entries()].sort((a, b) => a[0] - b[0]);
  const widths = sortedUsed.map(([code, { width }]) => `${code} [${width}]`).join(' ');
  const bfchar = sortedUsed.map(
    ([code, { src }]) => `<${code.toString(16).padStart(4, '0').toUpperCase()}> <${utf16BeHex(src)}>`,
  );
  const bfcharBlocks = [];
  for (let i = 0; i < bfchar.length; i += 100) {
    bfcharBlocks.push(
      `${Math.min(100, bfchar.length - i)} beginbfchar\n${bfchar.slice(i, i + 100).join('\n')}\nendbfchar`,
    );
  }
  const toUnicode = Buffer.from(
    [
      '/CIDInit /ProcSet findresource begin',
      '12 dict begin',
      'begincmap',
      '/CIDSystemInfo << /Registry (Adobe) /Ordering (UCS) /Supplement 0 >> def',
      '/CMapName /Adobe-Identity-UCS def',
      '/CMapType 2 def',
      '1 begincodespacerange',
      '<0000> <FFFF>',
      'endcodespacerange',
      ...bfcharBlocks,
      'endcmap',
      'CMapName currentdict /CMap defineresource pop',
      'end',
      'end',
    ].join('\n'),
    'ascii',
  );

  const objects = [
    Buffer.from('<< /Type /Catalog /Pages 2 0 R >>', 'ascii'),
    Buffer.from('<< /Type /Pages /Kids [3 0 R] /Count 1 >>', 'ascii'),
    Buffer.from(
      '<< /Type /Page /Parent 2 0 R /MediaBox [0 0 612 792] ' +
        '/Resources << /Font << /F1 5 0 R /F2 6 0 R >> >> /Contents 4 0 R >>',
      'ascii',
    ),
    Buffer.concat([
      Buffer.from(`<< /Length ${content.length} >>\nstream\n`, 'ascii'),
      content,
      Buffer.from('\nendstream', 'ascii'),
    ]),
    Buffer.from('<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>', 'ascii'),
    Buffer.from(
      `<< /Type /Font /Subtype /Type0 /BaseFont /${fontName} /Encoding /Identity-H ` +
        '/DescendantFonts [7 0 R] /ToUnicode 10 0 R >>',
      'ascii',
    ),
    Buffer.from(
      font.format === 'cff'
        ? `<< /Type /Font /Subtype /CIDFontType0 /BaseFont /${fontName} ` +
            '/CIDSystemInfo << /Registry (Adobe) /Ordering (Identity) /Supplement 0 >> ' +
            `/FontDescriptor 8 0 R /DW 1000 /W [${widths}] >>`
        : `<< /Type /Font /Subtype /CIDFontType2 /BaseFont /${fontName} ` +
            '/CIDSystemInfo << /Registry (Adobe) /Ordering (Identity) /Supplement 0 >> ' +
            `/FontDescriptor 8 0 R /DW 1000 /W [${widths}] /CIDToGIDMap /Identity >>`,
      'ascii',
    ),
    Buffer.from(
      `<< /Type /FontDescriptor /FontName /${fontName} /Ascent ${font.ascent} ` +
        `/Descent ${font.descent} /CapHeight ${font.capHeight} /Flags 4 ` +
        `/FontBBox [${font.bbox.join(' ')}] /StemV 80 /${font.format === 'cff' ? 'FontFile3' : 'FontFile2'} 9 0 R >>`,
      'ascii',
    ),
    Buffer.concat([
      Buffer.from(
        font.format === 'cff'
          ? `<< /Length ${font.data.length} /Subtype /CIDFontType0C >>\nstream\n`
          : `<< /Length ${font.data.length} /Length1 ${font.data.length} >>\nstream\n`,
        'ascii',
      ),
      font.data,
      Buffer.from('\nendstream', 'ascii'),
    ]),
    Buffer.concat([
      Buffer.from(`<< /Length ${toUnicode.length} >>\nstream\n`, 'ascii'),
      toUnicode,
      Buffer.from('\nendstream', 'ascii'),
    ]),
    Buffer.from(`<< /Title (${pdfEscape(title)}) /Producer (fixture-generator) >>`, 'ascii'),
  ];
  const parts = [Buffer.from('%PDF-1.4\n', 'ascii')];
  const offsets = [];
  objects.forEach((body, index) => {
    offsets.push(parts.reduce((total, part) => total + part.length, 0));
    parts.push(Buffer.from(`${index + 1} 0 obj\n`, 'ascii'), body, Buffer.from('\nendobj\n', 'ascii'));
  });
  const xrefPos = parts.reduce((total, part) => total + part.length, 0);
  let xref = `xref\n0 ${objects.length + 1}\n0000000000 65535 f \n`;
  for (const offset of offsets) {
    xref += `${String(offset).padStart(10, '0')} 00000 n \n`;
  }
  parts.push(
    Buffer.from(xref, 'ascii'),
    Buffer.from(`trailer\n<< /Size ${objects.length + 1} /Root 1 0 R /Info 11 0 R >>\n`, 'ascii'),
    Buffer.from(`startxref\n${xrefPos}\n%%EOF`, 'ascii'),
  );
  return Buffer.concat(parts);
}

