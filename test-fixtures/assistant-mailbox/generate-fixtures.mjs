function arabicPairJoins(a, b) {
  return ARABIC_JOINING[a] === 'D' && (ARABIC_JOINING[b] === 'D' || ARABIC_JOINING[b] === 'R');
}

function shapeArabicWord(word) {
  // Returns glyphs in logical order: [{ cp, src }] where cp is a
  // presentation-form code point and src the logical character it stands
  // for. One glyph per character, lam-alef pairs included (the lam form
  // and the alef final form join up on the page): extraction stays a
  // clean one-character-per-glyph mapping.
  const glyphs = [];
  for (let i = 0; i < word.length; i++) {
    const char = word[i];
    const joinsBack = i > 0 && arabicPairJoins(word[i - 1], char);
    const joinsForward = i + 1 < word.length && arabicPairJoins(char, word[i + 1]);
    const form = joinsBack && joinsForward ? 'med' : joinsBack ? 'fin' : joinsForward ? 'ini' : 'iso';
    const forms = ARABIC_FORMS[char];
    if (forms === undefined) {
      throw new Error(`no presentation forms for ${char}`);
    }
    glyphs.push({ cp: forms[form] ?? forms.iso, src: char });
  }
  return glyphs;
}

function shapeArabicLine(line) {
  // Visual order for one right-to-left line: reverse the space-separated
  // tokens; inside a token, reverse its runs (Arabic letter runs are
  // shaped, other runs such as numbers stay in reading order). Returns
  // glyphs as [{ cp, src }] in drawing order.
  const glyphs = [];
  const tokens = line.split(' ');
  tokens.forEach((token, tokenIndex) => {
    if (tokenIndex > 0) {
      glyphs.push({ cp: 0x20, src: ' ' });
    }
    const visualToken = tokens[tokens.length - 1 - tokenIndex];
    const runs = [];
    for (const char of visualToken) {
      const arabic = ARABIC_JOINING[char] !== undefined;
      const last = runs[runs.length - 1];
      if (last !== undefined && last.arabic === arabic) {
        last.text += char;
      } else {
        runs.push({ arabic, text: char });
      }
    }
    for (const run of runs.reverse()) {
      if (run.arabic) {
        glyphs.push(...shapeArabicWord(run.text).reverse());
      } else {
        for (const char of run.text) {
          glyphs.push({ cp: char.codePointAt(0), src: char });
        }
      }
    }
  });
  return glyphs;
}

