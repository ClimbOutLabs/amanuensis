// Non-ASCII mail: RFC 2047 headers and quoted-printable bodies
// ---------------------------------------------------------------------------

function encodeHeaderWords({ text, charset, bufferEncoding }) {
  // RFC 2047 encoded words, split so each word stays within its length
  // cap, folded with a continuation line.
  const isAscii = [...text].every(char => char.codePointAt(0) < 0x80);
  if (isAscii) {
    return text;
  }
  const words = [];
  let chunk = '';
  let chunkBytes = 0;
  for (const char of text) {
    const charBytes = Buffer.byteLength(char, bufferEncoding);
    if (chunk !== '' && chunkBytes + charBytes > 42) {
      words.push(chunk);
      chunk = '';
      chunkBytes = 0;
    }
    chunk += char;
    chunkBytes += charBytes;
  }
  if (chunk !== '') {
    words.push(chunk);
  }
  return words.map(word => `=?${charset}?B?${Buffer.from(word, bufferEncoding).toString('base64')}?=`).join('\r\n ');
}

function formatSender({ name, address, charset = 'UTF-8', bufferEncoding = 'utf8' }) {
  return `${encodeHeaderWords({ text: name, charset, bufferEncoding })} <${address}>`;
}

function quotedPrintableEncode(buffer) {
  // RFC 2045 quoted-printable with soft line breaks: encoded lines stay at
  // or under 76 characters. Input uses \n for line breaks.
  const lines = [];
  let current = '';
  const pushToken = token => {
    if (current.length + token.length > 75) {
      if (current.endsWith(' ')) {
        current = `${current.slice(0, -1)}=20`;
      }
      lines.push(`${current}=`);
      current = '';
    }
    current += token;
  };
  for (const byte of buffer) {
    if (byte === 0x0a) {
      if (current.endsWith(' ')) {
        current = `${current.slice(0, -1)}=20`;
      }
      lines.push(current);
      current = '';
    } else if (byte === 0x3d || byte < 0x20 || byte > 0x7e) {
      pushToken(`=${byte.toString(16).toUpperCase().padStart(2, '0')}`);
    } else {
      pushToken(String.fromCharCode(byte));
    }
  }
  lines.push(current);
  return lines.join('\r\n');
}

function emlI18n({
  from,
  to,
  date,
  subject,
  msgid,
  body,
  charset = 'UTF-8',
  bufferEncoding = 'utf8',
  extraHeaders = [],
  attachments = [],
}) {
  const head = [
    `From: ${from}`,
    `To: ${to}`,
    `Date: ${date}`,
    `Subject: ${encodeHeaderWords({ text: subject, charset, bufferEncoding })}`,
    `Message-ID: ${msgid}`,
    ...extraHeaders,
    'MIME-Version: 1.0',
  ];
  const bodyQp = quotedPrintableEncode(Buffer.from(body, bufferEncoding));
  if (attachments.length === 0) {
    return crlfJoin([
      ...head,
      `Content-Type: text/plain; charset=${charset}`,
      'Content-Transfer-Encoding: quoted-printable',
      '',
      bodyQp,
      '',
    ]);
  }
  const parts = [
    ...head,
    `Content-Type: multipart/mixed; boundary="${BOUNDARY}"`,
    '',
    `--${BOUNDARY}`,
    `Content-Type: text/plain; charset=${charset}`,
    'Content-Transfer-Encoding: quoted-printable',
    '',
    bodyQp,
  ];
  for (const { filename, mime, data } of attachments) {
    parts.push(
      `--${BOUNDARY}`,
      `Content-Type: ${mime}; name="${filename}"`,
      'Content-Transfer-Encoding: base64',
      `Content-Disposition: attachment; filename="${filename}"`,
      '',
      base64Lines(data),
    );
  }
  parts.push(`--${BOUNDARY}--`, '');
  return crlfJoin(parts);
}

