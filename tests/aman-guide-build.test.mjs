import assert from 'node:assert/strict';
import { mkdir, mkdtemp, readFile, rm, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import path from 'node:path';
import test from 'node:test';
import { fileURLToPath } from 'node:url';
import { buildAmanGuide } from '../scripts/build-aman-guide.mjs';

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');

const TOUR_FIXTURE = `
export type TourCapabilities = {
  email: boolean;
  sandbox: boolean;
};
const ADD_NUMBERS: TourPrompt = { key: 'code', title: 'Run code', prompt: 'Add numbers.', needs: ['sandbox'] };
export const GENERAL_CARDS: readonly TourPrompt[] = [
  { key: 'brief', title: 'Your morning brief', prompt: BRIEF_PROMPT },
  { key: 'email', title: 'Handle your email', prompt: 'Read my mail.', needs: ['email'] },
];
export const HOME_TOPICS: Record<HomeTopicId, { label: string; cards: readonly TourPrompt[] }> = {
  productivity: { label: 'Productivity', cards: [ADD_NUMBERS] },
};
`;

async function fixture({ tour = TOUR_FIXTURE, topics, requiredCards = [] }) {
  const dir = await mkdtemp(path.join(tmpdir(), 'aman-guide-'));
  const topicsDir = path.join(dir, 'topics');
  await mkdir(topicsDir);
  await writeFile(path.join(dir, 'tourPrompts.ts'), tour);
  await writeFile(path.join(dir, 'required-cards.json'), JSON.stringify(requiredCards));
  for (const [name, text] of Object.entries(topics)) {
    await writeFile(path.join(topicsDir, name), text);
  }
  const outPath = path.join(dir, 'out', 'knowledgePack.generated.ts');
  return {
    dir,
    options: {
      tourPath: path.join(dir, 'tourPrompts.ts'),
      topicsDir,
      requiredCardsPath: path.join(dir, 'required-cards.json'),
      outPath,
      repoRoot,
    },
    outPath,
  };
}

function topic({ id, title = `Title ${id}`, covers = '', body = 'Plain words.' }) {
  return `---\nid: ${id}\ntitle: ${title}\ncovers: ${covers}\n---\n${body}\n`;
}

test('the real repo build writes the pack and every required card has a page', async () => {
  const outDir = await mkdtemp(path.join(tmpdir(), 'aman-guide-real-'));
  try {
    const outPath = path.join(outDir, 'knowledgePack.generated.ts');
    const result = await buildAmanGuide({ repoRoot, outPath });
    assert.ok(result.topics.length > 0);
    const covered = new Set(result.topics.flatMap(item => item.covers));
    assert.deepEqual(
      result.uncoveredKeys,
      result.tourKeys.filter(key => !covered.has(key)),
    );
    const required = JSON.parse(
      await readFile(path.join(repoRoot, 'packages/trueforge/guide/required-cards.json'), 'utf8'),
    );
    for (const key of required) {
      assert.ok(covered.has(key), `required Tour card "${key}" has no guide page`);
    }
    const written = await readFile(outPath, 'utf8');
    assert.match(written, /export const AMAN_GUIDE_TOPICS/);
    assert.match(written, /Generated by scripts\/build-aman-guide\.mjs/);
  } finally {
    await rm(outDir, { recursive: true, force: true });
  }
});

test('reads Tour cards through the constants and topics that hold them', async () => {
  const fx = await fixture({ topics: { 'a.md': topic({ id: 'a', covers: 'brief, code, email' }) } });
  try {
    const result = await buildAmanGuide(fx.options);
    assert.deepEqual(result.tourKeys, ['brief', 'email', 'code']);
    assert.deepEqual(result.uncoveredKeys, []);
  } finally {
    await rm(fx.dir, { recursive: true, force: true });
  }
});

test('a Tour card with no guide page is a warning, not a failure', async () => {
  const fx = await fixture({ topics: { 'a.md': topic({ id: 'a', covers: 'brief' }) } });
  try {
    const result = await buildAmanGuide(fx.options);
    assert.deepEqual(result.uncoveredKeys, ['email', 'code']);
  } finally {
    await rm(fx.dir, { recursive: true, force: true });
  }
});

test('the build fails when a required Tour card has no guide page', async () => {
  const fx = await fixture({
    requiredCards: ['brief', 'email'],
    topics: { 'a.md': topic({ id: 'a', covers: 'brief' }) },
  });
  try {
    await assert.rejects(buildAmanGuide(fx.options), /Tour card "email" must have a guide page/);
  } finally {
    await rm(fx.dir, { recursive: true, force: true });
  }
});

test('the build fails when the required list names a card that does not exist', async () => {
  const fx = await fixture({
    requiredCards: ['flying-cars'],
    topics: { 'a.md': topic({ id: 'a', covers: 'brief' }) },
  });
  try {
    await assert.rejects(buildAmanGuide(fx.options), /lists "flying-cars", which is not a Tour card/);
  } finally {
    await rm(fx.dir, { recursive: true, force: true });
  }
});

