import assert from 'node:assert/strict';
import { mkdir, mkdtemp, readFile, rm, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import path from 'node:path';
import test from 'node:test';
import { fileURLToPath } from 'node:url';
import { buildAmanGuide } from '../scripts/build-aman-guide.mjs';

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');

const TOUR_FIXTURE = `
export type TourCapabilities = {
  email: boolean;
  sandbox: boolean;
};
export const TRY_A_DAY_PROMPTS: readonly TourPrompt[] = [
  { key: 'brief', label: 'Your morning brief', prompt: 'Good morning.' },
];
export const CAPABILITY_PROMPTS: readonly TourPrompt[] = [
  { key: 'email', label: 'Handle your email', prompt: 'Read my mail.', needs: 'email' },
  { key: 'code', label: 'Run code', prompt: 'Add numbers.', needs: 'sandbox' },
];
`;

async function fixture({ tour = TOUR_FIXTURE, topics }) {
  const dir = await mkdtemp(path.join(tmpdir(), 'aman-guide-'));
  const topicsDir = path.join(dir, 'topics');
  await mkdir(topicsDir);
  await writeFile(path.join(dir, 'AmanTour.tsx'), tour);
  for (const [name, text] of Object.entries(topics)) {
    await writeFile(path.join(topicsDir, name), text);
  }
  const outPath = path.join(dir, 'out', 'knowledgePack.generated.ts');
  return {
    dir,
    options: { tourPath: path.join(dir, 'AmanTour.tsx'), topicsDir, outPath, repoRoot },
    outPath,
  };
}

function topic({ id, title = `Title ${id}`, covers = '', body = 'Plain words.' }) {
  return `---\nid: ${id}\ntitle: ${title}\ncovers: ${covers}\n---\n${body}\n`;
}

test('the real repo build covers every Tour card and writes the pack', async () => {
  const outDir = await mkdtemp(path.join(tmpdir(), 'aman-guide-real-'));
  try {
    const outPath = path.join(outDir, 'knowledgePack.generated.ts');
    const result = await buildAmanGuide({ repoRoot, outPath });
    assert.ok(result.topics.length > 0);
    const covered = new Set(result.topics.flatMap(item => item.covers));
    for (const key of result.tourKeys) {
      assert.ok(covered.has(key), `Tour card "${key}" has no guide entry`);
    }
    const written = await readFile(outPath, 'utf8');
    assert.match(written, /export const AMAN_GUIDE_TOPICS/);
    assert.match(written, /Generated by scripts\/build-aman-guide\.mjs/);
  } finally {
    await rm(outDir, { recursive: true, force: true });
  }
});

test('the build fails when a Tour card has no guide entry', async () => {
  const fx = await fixture({ topics: { 'a.md': topic({ id: 'a', covers: 'brief' }) } });
  try {
    await assert.rejects(buildAmanGuide(fx.options), /Tour card "email" has no guide entry/);
  } finally {
    await rm(fx.dir, { recursive: true, force: true });
  }
});

test('the build fails when an entry names a capability that does not exist', async () => {
  const fx = await fixture({
    topics: {
      'a.md': topic({ id: 'a', covers: 'brief, email, code' }),
      'b.md': topic({ id: 'b', covers: 'flying-cars' }),
    },
  });
  try {
    await assert.rejects(buildAmanGuide(fx.options), /names "flying-cars", which is not a Tour card/);
  } finally {
    await rm(fx.dir, { recursive: true, force: true });
  }
});

test('the build fails when a Tour card needs a capability the type does not declare', async () => {
  const tour = TOUR_FIXTURE.replace("needs: 'sandbox'", "needs: 'teleport'");
  const fx = await fixture({ tour, topics: { 'a.md': topic({ id: 'a', covers: 'brief, email, code' }) } });
  try {
    await assert.rejects(buildAmanGuide(fx.options), /needs "teleport", which TourCapabilities does not declare/);
  } finally {
    await rm(fx.dir, { recursive: true, force: true });
  }
});

test('the build fails on a duplicate topic id or an empty body', async () => {
  const dupe = await fixture({
    topics: { 'a.md': topic({ id: 'a', covers: 'brief, email, code' }), 'b.md': topic({ id: 'a' }) },
  });
  const empty = await fixture({ topics: { 'a.md': topic({ id: 'a', covers: 'brief, email, code', body: '' }) } });
  try {
    await assert.rejects(buildAmanGuide(dupe.options), /Duplicate guide topic id "a"/);
    await assert.rejects(buildAmanGuide(empty.options), /has an empty body/);
  } finally {
    await rm(dupe.dir, { recursive: true, force: true });
    await rm(empty.dir, { recursive: true, force: true });
  }
});
