/**
 * Ids that no longer appear in the picker, mapped to the theme they now mean.
 * Saved preferences and host configs use these, so they must keep resolving.
 */
const LEGACY_PRESET_IDS = new Map<string, ThemePreset>([
  ['trueforge', 'paper'],
  ['claude', 'paper'],
  ['gemini', 'paper'],
  ['sunset', 'paper'],
  ['volt', 'paper'],
  ['chatgpt', 'high-contrast'],
  ['mint', 'high-contrast'],
]);

/** Resolves a current or legacy preset id. Returns `undefined` for anything unknown. */
export function resolveThemePreset(value: string): ThemePreset | undefined {
  return THEME_PRESET_IDS.find(id => id === value) ?? LEGACY_PRESET_IDS.get(value);
}

export function resolvePresetTokens(preset: ThemePreset | undefined, mode: 'light' | 'dark'): SemanticTokens {
  return PRESETS[preset ?? DEFAULT_THEME_PRESET][mode];
}
